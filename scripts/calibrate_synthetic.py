#!/usr/bin/env python3
"""Rebuild embedded calibration records from the four larger probation cases."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = ['r10_p5_m5_s2.txt', 'r30_p15_m15_s3.txt',
         'r100_p50_m50_s4.txt', 'r240_p120_m120_s5.txt']
cases = []
for name in FILES:
    path = ROOT / 'data/probation' / name
    lines = iter(path.read_text().splitlines())
    k, n, m = map(int, next(lines).split())
    taxis = [list(map(float, next(lines).split())) for _ in range(k)]
    passengers = [list(map(float, next(lines).split())) for _ in range(n)]
    parcels = [list(map(float, next(lines).split())) for _ in range(m)]
    v = k + 2*(n+m)
    times = [list(map(float, next(lines).split())) for _ in range(v)]
    costs = [list(map(float, next(lines).split())) for _ in range(v)]
    cases.append(dict(file=name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                      capacities=[r[1] for r in taxis], passengers=passengers,
                      parcels=parcels, times=times, costs=costs))

fits = {}
for kind, revenue_column in [('passengers', 5), ('parcels', 8)]:
    # Every case contributes total weight one, regardless of its request count.
    values = [(case['costs'][int(r[0])-1][int(r[1])-1], r[revenue_column],
               1/len(case[kind])) for case in cases for r in case[kind]]
    total = sum(w for x, y, w in values)
    mx = sum(x*w for x,y,w in values)/total
    my = sum(y*w for x,y,w in values)/total
    a = sum(w*(x-mx)*(y-my) for x,y,w in values)/sum(w*(x-mx)**2 for x,y,w in values)
    fits[kind] = (a, my-a*mx)

header = ['// Generated by scripts/calibrate_synthetic.py; do not edit records manually.',
          '#pragma once', '#include <vector>', 'namespace soict::calibration {',
          'struct PassengerRecord { double earliest, width, service, residual; };',
          'struct ParcelRecord { double weight, earliest, width, delivery_width, service, delta, residual; };',
          'struct Case { std::vector<double> capacities; std::vector<PassengerRecord> passengers; std::vector<ParcelRecord> parcels; };']
for kind, (a,b) in fits.items():
    prefix = 'passenger' if kind == 'passengers' else 'parcel'
    header.append(f'inline constexpr double {prefix}_slope = {a:.17g}, {prefix}_intercept = {b:.17g};')
header.append('inline const std::vector<Case> cases = {')
for case in cases:
    header.append('  { {' + ', '.join(f'{x:g}' for x in case['capacities']) + '}, {')
    a,b = fits['passengers']
    for p,d,e,l,s,revenue in case['passengers']:
        c = case['costs'][int(p)-1][int(d)-1]
        header.append(f'    {{{e:g}, {l-e:g}, {s:g}, {revenue-a*c-b:.17g}}},')
    header.append('  }, {')
    a,b = fits['parcels']
    for p,d,w,ep,lp,ed,ld,s,revenue in case['parcels']:
        t = case['times'][int(p)-1][int(d)-1]
        c = case['costs'][int(p)-1][int(d)-1]
        delta = ed-ep-s-t
        if not 0 <= delta <= 10 or delta != int(delta):
            raise ValueError('unexpected parcel delivery offset')
        header.append(f'    {{{w:g}, {ep:g}, {lp-ep:g}, {ld-ed:g}, {s:g}, {delta:g}, {revenue-a*c-b:.17g}}},')
    header.append('  } },')
header.extend(['};', '} // namespace soict::calibration', ''])
(ROOT/'src/io/SyntheticCalibration.hpp').write_text('\n'.join(header))
metadata = dict(sources=[dict(file=c['file'],sha256=c['sha256']) for c in cases],
                case_weight='equal', revenue_fits={k:dict(slope=a,intercept=b) for k,(a,b) in fits.items()})
(ROOT/'data/probation/calibration.json').write_text(json.dumps(metadata,indent=2)+'\n')
